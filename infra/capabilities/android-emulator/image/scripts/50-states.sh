#!/bin/bash
# Build /opt/ace/states.yaml: the named states (one per CommCare APK version)
# baked into this image. Moved from ace-web infra/mobile-ami/scripts/
# 50-bake-snapshot.sh (renamed: it has not baked a snapshot since 2026-05-10).
#
# Readers:
#   - ace-emulator-launch, which resolves the lease's state to an APK on boot;
#   - the boot hook (ace-capability-boot), which refuses a state not listed here;
#   - `ace-mobile diagnose`, which reports the catalog.
# capability.yaml's `params.state.enum` must list exactly these names, and its
# default must be the first; test/infra/android-emulator-capability.test.ts
# checks that against variables.pkr.hcl's `commcare_versions`.
#
# No emulator boot, no snapshot, no registration happens in the bake: every
# lease cold-boots a fresh -wipe-data AVD, installs its state's APK, and the
# Connect test user is registered on demand (`ace-mobile register-test-user`).
#
# Idempotent. Reads COMMCARE_VERSIONS from Packer (the same var as
# 40-commcare-apk.sh). APK_ROOT / STATES_YAML / STATES_OWNER are overridable so
# the unit tests can run this exact script against a temp dir.
set -euo pipefail

: "${COMMCARE_VERSIONS:?COMMCARE_VERSIONS is required}"

APK_ROOT="${APK_ROOT:-/opt/ace/apks}"
STATES_YAML="${STATES_YAML:-/opt/ace/states.yaml}"
STATES_OWNER="${STATES_OWNER-ubuntu:ubuntu}"

IFS=',' read -ra VERSIONS <<< "$COMMCARE_VERSIONS"

{
  echo "# Auto-generated by 50-states.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
  echo "# Catalog of named states (= CommCare APK versions) this image can boot."
  echo "# Default = first version listed; a lease without params.state boots it."
  echo "default: cc-$(echo "${VERSIONS[0]}" | tr -d ' ')"
  echo "states:"
} > "$STATES_YAML"

for VERSION in "${VERSIONS[@]}"; do
  VERSION="$(echo "$VERSION" | tr -d ' ')"
  STATE_NAME="cc-${VERSION}"
  APK_PATH="$APK_ROOT/$VERSION/commcare.apk"
  if [[ ! -f "$APK_PATH" ]]; then
    echo "ERROR: missing APK for $VERSION at $APK_PATH" >&2
    exit 1
  fi
  CC_SHA256="$(cat "$APK_PATH.sha256")"

  cat >> "$STATES_YAML" <<YAML
  - name: ${STATE_NAME}
    snapshot: cold-boot-stage
    commcare_version: "${VERSION}"
    commcare_apk_sha256: ${CC_SHA256}
    apk_path: ${APK_PATH}
    description: "CommCare ${VERSION}: cold boot (-wipe-data) + APK install; test user registered on demand."
YAML
done

if [[ -n "$STATES_OWNER" ]]; then
  chown "$STATES_OWNER" "$STATES_YAML"
fi

echo "===================================================================="
echo "States manifest built for ${#VERSIONS[@]} version(s):"
cat "$STATES_YAML"
echo "===================================================================="
